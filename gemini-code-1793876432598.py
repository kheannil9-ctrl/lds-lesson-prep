import streamlit as st
import google.generativeai as genai

# --- ตั้งค่าหน้าเว็บ ---
st.set_page_config(
    page_title="LDS Lesson Prep - ระบบช่วยเตรียมบทเรียน",
    page_icon="📖",
    layout="centered"
)

# --- ดึง API Key ---
# ดึงจาก Secrets ของ Streamlit Cloud เพื่อไม่ให้สมาชิกต้องกรอกเอง
api_key = st.secrets.get("GEMINI_API_KEY")

if not api_key:
    # เผื่อกรณีทดสอบในเครื่องส่วนตัว สามารถกรอกผ่าน Sidebar ได้
    api_key = st.sidebar.text_input("กรอก Gemini API Key (สำหรับผู้ดูแล):", type="password")

if api_key:
    genai.configure(api_key=api_key)

# --- ส่วนหัวและคำแนะนำเบื้องต้น ---
st.title("📖 ระบบช่วยเตรียมบทเรียน (LDS Lesson Prep)")
st.caption("แปลงสุนทรพจน์การประชุมใหญ่ (General Conference) เป็นโครงร่างการสอนสำหรับครูมือใหม่")

st.info(
    "💡 **คำแนะนำสำหรับผู้สอน:** เครื่องมือนี้เป็นระบบ AI ที่ช่วยวางแนวทางบทเรียนเบื้องต้น "
    "การเตรียมบทเรียนจะมีประสิทธิภาพสูงสุดเมื่อท่านสวดอ้อนวอนและไตร่ตรองควบคู่ไปด้วย "
    "เพื่อให้พระวิญญาณทรงนำทางและปรับใช้ให้เหมาะกับสมาชิกในชั้นเรียนมากที่สุดครับ/ค่ะ"
)

# --- แบบฟอร์มกรอกข้อมูลบทเรียน ---
with st.form("lesson_form"):
    talk_input = st.text_area(
        "1. ระบุชื่อสุนทรพจน์, ผู้พูด หรือวางเนื้อหา/ลิงก์สุนทรพจน์ *",
        placeholder="ตัวอย่าง: ศรัทธาไม่ใช่เรื่องบังเอิญ แต่เป็นทางเลือก - เอ็ลเดอร์ นีล แอล. แอนเดอร์เซน (หรือวางเนื้อหาสุนทรพจน์ลงที่นี่)",
        height=120
    )

    col1, col2 = st.columns(2)
    with col1:
        target_class = st.selectbox(
            "2. กลุ่มชั้นเรียนที่สอน *",
            [
                "โรงเรียนวันอาทิตย์",
                "โควรัมเอ็ลเดอร์",
                "สมาคมสงเคราะห์",
                "เยาวชนชาย / เยาวชนหญิง",
                "ปฐมวัย",
                "ชั้นเรียนอื่น ๆ"
            ]
        )
    with col2:
        duration = st.selectbox(
            "3. เวลาในการสอน *",
            ["25 นาที", "30 นาที", "45 นาที", "60 นาที", "เวลาอื่น ๆ"]
        )

    teaching_styles = st.multiselect(
        "4. รูปแบบการสอนที่ต้องการ (เลือกได้มากกว่า 1 ข้อ)",
        [
            "เน้นสนทนาชวนคิดและแบ่งปันประสบการณ์ (คำถามปลายเปิด)",
            "เน้นใช้อุปกรณ์ช่วยสอนหรือเรื่องเล่าเปรียบเทียบ (Object Lesson)",
            "เน้นแบ่งกลุ่มย่อยค้นคว้าข้อพระคัมภีร์",
            "เน้นการนำไปใช้จริงและการตั้งเป้าหมายในชีวิต",
            "เน้นสรุปประเด็นกระชับ กึ่งบรรยายพร้อมคำถามนำ (เหมาะสำหรับครูมือใหม่)",
            "เน้นเกมสันทนาการหรือกิจกรรมจำลองสถานการณ์"
        ],
        default=["เน้นสนทนาชวนคิดและแบ่งปันประสบการณ์ (คำถามปลายเปิด)"]
    )

    extra_notes = st.text_input(
        "5. รายละเอียดเพิ่มเติม (ถ้ามี)",
        placeholder="เช่น อยากเน้นเรื่องการอธิษฐานเป็นพิเศษ, ผู้เรียนส่วนใหญ่เป็นสมาชิกใหม่"
    )

    submit_button = st.form_submit_button("✨ สร้างโครงร่างบทเรียน", use_container_width=True)

# --- ระบบประมวลผล ---
if submit_button:
    if not api_key:
        st.error("⚠️ ยังไม่ได้ตั้งค่า Gemini API Key กรุณาตั้งค่าใน Streamlit Secrets หรือใส่ในแถบด้านข้าง")
    elif not talk_input.strip():
        st.warning("⚠️ กรุณาระบุชื่อสุนทรพจน์หรือเนื้อหาที่ต้องการสอนก่อนกดปุ่มครับ")
    else:
        with st.spinner("กำลังวิเคราะห์เนื้อหาสุนทรพจน์และจัดทำโครงร่างบทเรียน..."):
            styles_str = ", ".join(teaching_styles) if teaching_styles else "ตามความเหมาะสมของเนื้อหา"
            
            system_instruction = f"""
คุณคือผู้เชี่ยวชาญการออกแบบแผนการสอนของศาสนจักรของพระเยซูคริสต์แห่งวิสุทธิชนยุคสุดท้าย โดยเน้นช่วยครูมือใหม่ให้สอนได้อย่างมั่นใจ

ข้อมูลบทเรียน:
- สุนทรพจน์/เนื้อหา: {talk_input}
- ชั้นเรียน: {target_class}
- เวลาสอน: {duration}
- สไตล์การสอน: {styles_str}
- ข้อกำหนดเพิ่มเติม: {extra_notes}

กฎเหล็กสำคัญ:
1. ยึดเนื้อหาจริงเท่านั้น: แก่นหลักธรรมและคำถามต้องมาจากสุนทรพจน์ที่ระบุเท่านั้น ห้ามนำทฤษฎีภายนอกมาปน
2. ข้อพระคัมภีร์: ใช้เฉพาะข้อพระคัมภีร์ที่ปรากฏในเนื้อหาหรือเชิงอรรถ (Footnotes) ของสุนทรพจน์นี้เท่านั้น ห้ามแต่งเติมหรือหยิบยกข้อพระคัมภีร์ภายนอกเองเด็ดขาด (ยกเว้นกรณีสุนทรพจน์นี้อ้างถึงสุนทรพจน์การประชุมใหญ่อื่น ให้นำมาใช้ได้)
3. มีตัวอย่างคำพูดจริง: ในแต่ละช่วง ให้เขียน '💡 ตัวอย่างประโยคที่ครูพูดได้จริง' เพื่อให้ครูอ่านตามได้ทันที

ให้จัดโครงสร้างผลลัพธ์เป็น Markdown ดังนี้:
1. ข้อมูลภาพรวมของบทเรียน (ชื่อบทเรียน, ผู้พูด, ชั้นเรียน, เวลา, วัตถุประสงค์หลัก 1 ประโยค)
2. โครงสร้างการสอนและเวลาอย่างละเอียด (แบ่งช่วงเวลาตามนาทีจริงให้ครบ {duration}):
   - ช่วงเปิดบทเรียน (Hook & คำถามเปิดใจ พร้อมตัวอย่างประโยคพูดจริง)
   - ช่วงเนื้อหาและหลักธรรมสำคัญ (แบ่งเป็น 2-3 ประเด็นหลัก โดยแต่ละข้อต้องมี: ข้อความโควทสำคัญจากสุนทรพจน์, ข้อพระคัมภีร์ที่สุนทรพจน์อ้างอิง, คำถามสนทนา/กิจกรรม, ตัวอย่างประโยคพูดนำ)
   - ช่วงสรุป เชื้อเชิญ และเป็นพยาน (คำเชื้อเชิญให้ลงมือปฏิบัติในสัปดาห์นี้ และแนวทางกล่าวคำประจักษ์พยาน)
3. แผนสำรองเรื่องเวลาสำหรับครู (กรณีสอนไม่ทันต้องตัดตรงไหน / กรณีเวลาเหลือมีคำถามเสริมอะไรจากสุนทรพจน์)
4. ปิดท้ายด้วยข้อความเตือนใจนี้เสมอ:
> 💡 **ข้อเตือนใจสำหรับผู้สอน:** แผนการสอนนี้จัดทำขึ้นโดย AI เพื่อเป็นตัวช่วยตั้งต้นและอาจมีข้อผิดพลาดได้ ขอแนะนำให้ท่านสวดอ้อนวอนและไตร่ตรองควบคู่ไปด้วยเสมอ พร้อมปรับเปลี่ยนเนื้อหาตามการทรงนำของพระวิญญาณบริสุทธิ์เพื่อตอบโจทย์ผู้เรียนในชั้นเรียนอย่างแท้จริงครับ/ค่ะ
"""
            try:
                model = genai.GenerativeModel("gemini-1.5-flash")
                response = model.generate_content(system_instruction)
                
                st.success("✅ สร้างแผนการสอนสำเร็จแล้ว!")
                st.markdown(response.text)
                
                # ปุ่มดาวน์โหลดเอกสาร
                st.download_button(
                    label="📥 ดาวน์โหลดแผนการสอนเป็นไฟล์ข้อความ (.txt)",
                    data=response.text,
                    file_name="lesson_plan.txt",
                    mime="text/plain",
                    use_container_width=True
                )
            except Exception as e:
                st.error(f"เกิดข้อผิดพลาดในการสร้างเนื้อหา: {e}")